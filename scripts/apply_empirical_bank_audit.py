def update_banks_dataset(dataset_path):
    with open(dataset_path, "r", encoding="utf-8") as f:
        banks = json.load(f)

    updated_count = 0
    for b in banks:
        code = b.get("short_code", "").upper()
        if code in AUDITED_METRICS:
            meta = AUDITED_METRICS[code]
            b["npl_ratio_pct"] = meta["npl_ratio_pct"]
            b["npl_category"] = meta["npl_category"]
            b["capital_adequacy_ratio_car"] = meta["capital_adequacy_ratio_car"]
            b["credit_rating"] = meta["credit_rating"]
            b["rating_score"] = meta["rating_score"]
            b["stability_tier"] = meta["stability_tier"]
            b["risk_label"] = meta["risk_label"]
            b["sovereign_backed"] = meta["sovereign_backed"]

            # Update rating agency
            if meta["stability_tier"] == "TIER_1_PRIME":
                b["rating_agency"] = "CRAB / CRISL (AAA Tier)"
            elif meta["stability_tier"] == "TIER_5_DISTRESSED":
                b["rating_agency"] = "Bangladesh Bank Supervisory AQR / BB Rating"
            else:
                b["rating_agency"] = "CRAB / CRISL / Emerging Credit Rating"

            # Recalculate true risk-adjusted score
            rate1y = b.get("fdr_rates", {}).get("1_year", 0)
            score = round(rate1y * ((meta["rating_score"] / 5.0) ** 0.65), 2)
            b["risk_adjusted_yield_score"] = score
            updated_count += 1

    with open(dataset_path, "w", encoding="utf-8") as f:
        json.dump(banks, f, indent=2)

    print(f"[✓] Successfully applied empirical financial audit to {updated_count}/{len(banks)} banks in {dataset_path}")
    return updated_count

